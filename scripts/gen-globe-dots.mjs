// One-off: bake the About globe's land dots into src/components/sections/globe-dots.ts.
//   node scripts/gen-globe-dots.mjs
// A Fibonacci sphere of N points is sampled against world-atlas land (50m) with d3-geo. The output
// stores only which Fibonacci indices are land, as a base64 bitset (the runtime regenerates the
// sphere from the index), plus a pre-projected SVG path of the front hemisphere for the static
// fallback (no WebGL, reduced motion, before the GL is ready), drawn from the same rest pose.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const N = 16000;
// Rest pose: the globe faces Pakistan with Lahore a little up and right of centre.
const REST = { lng: 70, lat: 24 };
const LAHORE = { lat: 31.5204, lng: 74.3587 };
const VB = 800; // fallback viewBox
const R = VB * 0.42; // sphere radius in the viewBox (the GL scene uses the same fraction)

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url), 'utf8'));
const land = feature(topo, topo.objects.land);

const GA = Math.PI * (3 - Math.sqrt(5));
const D = Math.PI / 180;

// Same formula as globe-scene.ts: unit vector (x right/east, y up/north, z towards the viewer at lng 0).
function fib(i) {
  const y = 1 - (2 * (i + 0.5)) / N;
  const r = Math.sqrt(1 - y * y);
  const t = i * GA;
  return [Math.cos(t) * r, y, Math.sin(t) * r];
}
const toLngLat = ([x, y, z]) => [Math.atan2(x, z) / D, Math.asin(y) / D];
const vec = (lat, lng) => [Math.cos(lat * D) * Math.sin(lng * D), Math.sin(lat * D), Math.cos(lat * D) * Math.cos(lng * D)];

// q = Rx(lat0) * Ry(-lng0) * p
function rotate([x, y, z], lng0, lat0) {
  const a = -lng0 * D;
  const x1 = x * Math.cos(a) + z * Math.sin(a);
  const z1 = -x * Math.sin(a) + z * Math.cos(a);
  const b = lat0 * D;
  return [x1, y * Math.cos(b) - z1 * Math.sin(b), y * Math.sin(b) + z1 * Math.cos(b)];
}

const bits = new Uint8Array(Math.ceil(N / 8));
const near = []; // fallback dots by depth: limb (smaller, lighter) and face
const far = [];
let count = 0;
for (let i = 0; i < N; i++) {
  const p = fib(i);
  if (!geoContains(land, toLngLat(p))) continue;
  bits[i >> 3] |= 1 << (i & 7);
  count++;
  const q = rotate(p, REST.lng, REST.lat);
  if (q[2] <= 0.02) continue;
  const sx = Math.round(VB / 2 + q[0] * R);
  const sy = Math.round(VB / 2 - q[1] * R);
  (q[2] > 0.45 ? near : far).push(`M${sx} ${sy}h0`);
}

const l = rotate(vec(LAHORE.lat, LAHORE.lng), REST.lng, REST.lat);
const pin = [(0.5 + (l[0] * R) / VB).toFixed(4), (0.5 - (l[1] * R) / VB).toFixed(4)];

const out = `// Generated by scripts/gen-globe-dots.mjs. Do not edit by hand.
// Land dots of a ${N}-point Fibonacci sphere (world-atlas land 50m): ${count} dots.
export const GLOBE_N = ${N};
/** Base64 bitset: bit i set when Fibonacci point i is land. */
export const GLOBE_LAND = '${Buffer.from(bits).toString('base64')}';
/** Rest pose (degrees): the globe's centre faces this point. */
export const GLOBE_REST = { lng: ${REST.lng}, lat: ${REST.lat} } as const;
export const LAHORE = { lat: ${LAHORE.lat}, lng: ${LAHORE.lng} } as const;
/** Sphere radius as a fraction of the frame width. */
export const GLOBE_RADIUS = ${R / VB};
/** Static fallback, front hemisphere at the rest pose, viewBox 0 0 ${VB} ${VB}. */
export const GLOBE_VB = ${VB};
export const GLOBE_FACE = '${near.join('')}';
export const GLOBE_LIMB = '${far.join('')}';
/** Lahore at the rest pose, as fractions of the frame (left, top). */
export const LAHORE_AT = [${pin.join(', ')}] as const;
`;
const dest = fileURLToPath(new URL('../src/components/sections/globe-dots.ts', import.meta.url));
writeFileSync(dest, out);
console.log(`${count} land dots of ${N}; ${near.length + far.length} in the fallback; ${(out.length / 1024).toFixed(1)} KB -> ${dest}`);
